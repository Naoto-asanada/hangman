"""DADSスライドの見本デッキを作る。新しい資料はこのファイルを写して中身を差し替える。

使い方: python3 build_sample.py out.pptx
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dads_pptx as d  # noqa: E402


def main(out):
    prs = d.new_deck()
    d.title_slide(prs, "営業DX推進計画 2027年度", "SFA定着と商談化率の改善",
                  "2026年10月　営業企画部")
    index = d.index_slide(prs, "目次", [(n, None) for n in [
        "エグゼクティブサマリ", "結論と根拠", "KPIダッシュボード", "シナリオ比較",
        "選択肢比較", "プラン比較", "推進ステップ", "データフロー", "KPIドライバー"]])

    targets = [
        d.exec_summary_slide(
            prs, "エグゼクティブサマリ",
            ["商談化率は前期比で2pt低下し、主因は初回接触から提案までの日数の長期化。",
             "SFAの入力率が62%にとどまり、案件の停滞を早期に検知できていない。",
             "入力項目を12から5に絞り、日次の停滞アラートを導入する。",
             "投資額1,200万円、12か月で回収できる見込み。"],
            [("−2pt", "商談化率（前期比）"), ("62%", "SFA入力率"), ("12か月", "投資回収期間")]),
        d.conclusion_reasons_slide(
            prs, "結論と根拠",
            "SFAの入力項目を5つに絞り、停滞アラートを導入すべきである。",
            [("入力負荷が定着の壁", "入力に1件あたり平均9分かかり、外出の多い担当者ほど入力率が低い。"),
             ("停滞の検知が遅い", "提案前で14日以上止まる案件が全体の31%あり、失注の6割を占める。"),
             ("小さく始められる", "既存SFAの設定変更で対応でき、追加ライセンスは不要。")]),
        d.kpi_slide(
            prs, "KPIダッシュボード",
            [("売上高", "4.2億円", "＋8%", "good"), ("商談化率", "18%", "−2pt", "bad"),
             ("SFA入力率", "62%", "＋5pt", "good"), ("平均商談日数", "41日", "±0日", "flat")],
            lead="2026年度上期実績",
            body=["商談化率のみ悪化。提案前の停滞案件が増えたことが主因。",
                  "SFA入力率は改善傾向だが、目標の85%には届いていない。"]),
        d.table_slide(
            prs, "シナリオ比較",
            [["観点", "悲観", "基準", "楽観"],
             ["予測値（件）", "75", "100", "125"],
             ["前提となる入力率", "65%", "80%", "90%"],
             ["必要な追加工数", "なし", "月20時間", "月40時間"],
             ["主なリスク", "現場の定着遅れ", "アラート過多", "運用負荷の増加"]],
            col_widths=[288, 288, 288, 288], highlight_col=2, highlight_label="採用",
            source="出典：2026年度上期 SFAデータ（社内）"),
        d.table_slide(
            prs, "選択肢比較",
            [["評価観点", "A：現行SFAの設定変更", "B：入力支援ツール追加", "C：SFA刷新"],
             ["初期費用", "300万円", "800万円", "3,500万円"],
             ["導入期間", "2か月", "4か月", "12か月"],
             ["入力時間の削減", "約50%", "約70%", "約70%"],
             ["現場の学習負荷", "小", "中", "大"]],
            col_widths=[264, 296, 296, 296], highlight_col=1),
        d.cards_slide(
            prs, "プラン比較",
            [("ライト", "月5万円", ["10ユーザーまで", "標準レポート", "メールサポート"]),
             ("スタンダード", "月12万円", ["50ユーザーまで", "停滞アラート", "API連携", "電話サポート"]),
             ("エンタープライズ", "個別見積", ["ユーザー無制限", "専任担当", "SLA保証"])],
            recommended=1),
        d.steps_slide(
            prs, "推進ステップ",
            [("現状把握", "入力率・停滞案件を部門別に集計する。"),
             ("項目の削減", "入力項目を12から5に絞る。"),
             ("アラート設定", "14日停滞で担当と上長に通知する。"),
             ("定着支援", "週次で入力率を共有し、未入力者を個別支援する。")]),
        d.flow3_slide(
            prs, "データフロー",
            ["名刺管理", "Webフォーム", "電話・訪問記録"],
            ("SFA（処理基盤）", ["案件の自動登録", "停滞の検知", "スコアリング"]),
            ["停滞アラート", "週次ダッシュボード", "経営レポート"]),
        d.tree_slide(
            prs, "KPIドライバー", "売上高",
            [("商談数", False, [("Web流入の増加", False), ("紹介制度の拡充", False)]),
             ("商談化率", True, [("停滞アラート", True), ("提案テンプレート整備", False)]),
             ("平均単価", False, [("上位プランの提案", False)])]),
    ]
    d.link_index(index, targets)
    prs.save(out)
    print(f"saved: {out} ({len(prs.slides)} slides)")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "dads_sample.pptx")
